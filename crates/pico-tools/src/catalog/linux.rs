/// Instantiates verified Linux catalog tools with default current-directory sandbox.
pub fn get_linux_catalog() -> Vec<Arc<dyn Tool>> {
    let root = std::env::current_dir().unwrap_or_else(|_| std::path::PathBuf::from("."));
    get_linux_catalog_with_sandbox(Arc::new(PathSandbox::new(vec![root], vec![])))
}

/// Instantiates verified Linux catalog tools with an explicit PathSandbox.
pub fn get_linux_catalog_with_sandbox(sandbox: Arc<PathSandbox>) -> Vec<Arc<dyn Tool>> {
    let mut tools: Vec<Arc<dyn Tool>> = Vec::with_capacity(48);

    for cat in LINUX_CATEGORIES {
        for action in cat.actions {
            let meta = ToolMetadata {
                canonical_id: format!("linux.{}.{}", cat.name, action.subaction),
                domain_category: cat.name.to_string(),
                target_os: TargetOs::Linux,
                description: action.description.to_string(),
                permission_tier: action.tier,
                latency_class: action.latency,
                reversibility: action.reversibility,
                parameters_schema: action.build_schema(),
                adapter_cmd: action.adapter_cmd.to_string(),
                adapter_args: action.adapter_args.to_string(),
            };
            tools.push(Arc::new(EcosystemTool::with_sandbox(meta, sandbox.clone())));
        }
    }

    tools
}
