pub fn get_windows_catalog_with_sandbox(sandbox: Arc<PathSandbox>) -> Vec<Arc<dyn Tool>> {
    let mut tools: Vec<Arc<dyn Tool>> = Vec::with_capacity(64);

    for cat in WINDOWS_CATEGORIES {
        for action in cat.actions {
            let meta = ToolMetadata {
                canonical_id: format!("windows.{}.{}", cat.name, action.subaction),
                domain_category: cat.name.to_string(),
                target_os: TargetOs::Windows,
                description: action.description.to_string(),
                permission_tier: action.tier,
                latency_class: action.latency,
                reversibility: action.reversibility,
                parameters_schema: action.build_schema(),
                adapter_cmd: action.adapter_cmd.to_string(),
                adapter_args: action.adapter_args.to_string(),
            };
            tools.push(Arc::new(EcosystemTool::with_sandbox(meta, sandbox.clone())));
        }
    }

    tools
}
