/// Instantiates verified Windows catalog tools with default current-directory sandbox.
pub fn get_windows_catalog() -> Vec<Arc<dyn Tool>> {
    let root = std::env::current_dir().unwrap_or_else(|_| std::path::PathBuf::from("."));
    get_windows_catalog_with_sandbox(Arc::new(PathSandbox::new(vec![root], vec![])))
}

